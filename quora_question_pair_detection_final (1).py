"""**Dataset Preview**"""

train.head()

"""## Insights

The training dataset contains question pairs along with their duplicate labels.

The testing dataset contains unseen question pairs used for prediction.

The target variable is **is_duplicate**, where:

- 1 = Duplicate Question
- 0 = Non-Duplicate Question

**Dataset Information**
"""

train.info()

train.describe(include='all')

"""## Insights

The dataset contains textual features representing two questions.

Most of the columns are object datatype because they store natural language text.

The target column is numerical.

**Missing Values**
"""

print(train.isnull().sum())

print()

